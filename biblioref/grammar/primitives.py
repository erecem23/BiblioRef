"""Transferable bibliography grammar primitives for BiblioRef v0.8.5-a.

These values describe observable/inferred structure.  They are deliberately
style-agnostic: no university or named citation style is encoded here.
"""

from enum import Enum


class GrammarPrimitive(str, Enum):
    AUTHOR_EXPLICIT = "AUTHOR_EXPLICIT"
    AUTHOR_INHERITED = "AUTHOR_INHERITED"
    TITLE_ONLY_SUCCESSOR = "TITLE_ONLY_SUCCESSOR"
    REPEATED_AUTHOR_MARKER = "REPEATED_AUTHOR_MARKER"
    YEAR_PARENTHETICAL = "YEAR_PARENTHETICAL"
    YEAR_BARE = "YEAR_BARE"
    YEAR_ONLY_START = "YEAR_ONLY_START"
    UNDATED_DATE = "UNDATED_DATE"
    NUMERIC_ENTRY_MARKER = "NUMERIC_ENTRY_MARKER"
    MARKER_ONLY_NUMERIC = "MARKER_ONLY_NUMERIC"
    NUMERIC_PREFIX_MARKER = "NUMERIC_PREFIX_MARKER"
    NUMERIC_COMMA_MARKER = "NUMERIC_COMMA_MARKER"
    BRACKET_ENTRY_MARKER = "BRACKET_ENTRY_MARKER"
    BRACKET_KEY_MARKER = "BRACKET_KEY_MARKER"
    INSTITUTIONAL_AUTHOR = "INSTITUTIONAL_AUTHOR"
    STANDARD_DOCUMENT_START = "STANDARD_DOCUMENT_START"
    WRAPPED_AUTHOR_LIST = "WRAPPED_AUTHOR_LIST"
    CONFERENCE_EVENT_CONTINUATION = "CONFERENCE_EVENT_CONTINUATION"
    WEB_RESOURCE_START = "WEB_RESOURCE_START"
    HANGING_INDENT = "HANGING_INDENT"
    SOURCE_METADATA_CONTINUATION = "SOURCE_METADATA_CONTINUATION"
    DOI_OR_URL = "DOI_OR_URL"
    CROSS_PAGE_CONTINUATION = "CROSS_PAGE_CONTINUATION"
    RUNNING_HEADER = "RUNNING_HEADER"
    RUNNING_FOOTER = "RUNNING_FOOTER"


__all__ = ["GrammarPrimitive"]
